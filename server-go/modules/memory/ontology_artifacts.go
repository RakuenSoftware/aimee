package memory

import (
	"fmt"
	"strconv"
	"strings"
)

// OntologyArtifacts generates migration data from the Go owner's seed. Native
// outputs are temporary ABI data for callers that have not yet been ported.
func OntologyArtifacts() (map[string]string, error) { return ontologyArtifacts(seedOntology) }

func ontologyArtifacts(seed []relTypeDef) (map[string]string, error) {
	if len(seed) == 0 {
		return nil, fmt.Errorf("empty ontology seed")
	}
	printable := func(s string) bool {
		for _, c := range []byte(s) {
			if c < 32 || c > 126 {
				return false
			}
		}
		return true
	}
	seen := map[string]bool{}
	correction := map[string]int{"supersede": 0, "hard_delete": 1, "immutable": 2}
	for _, r := range seed {
		if r.RelType == "" || seen[r.RelType] || normalizeRelType(r.RelType) != r.RelType {
			return nil, fmt.Errorf("invalid/duplicate relation %q", r.RelType)
		}
		seen[r.RelType] = true
		for _, s := range []string{r.RelType, r.Inverse, r.Correction, r.Category} {
			if !printable(s) {
				return nil, fmt.Errorf("non-printable seed text in %q", r.RelType)
			}
		}
		if _, ok := correction[r.Correction]; !ok || r.Sensitivity > SensSecret {
			return nil, fmt.Errorf("invalid seed policy for %s", r.RelType)
		}
		for _, kinds := range [][]NodeKind{r.HeadKinds, r.TailKinds} {
			if len(kinds) == 0 || len(kinds) > 8 {
				return nil, fmt.Errorf("invalid kinds for %s", r.RelType)
			}
			for _, kind := range kinds {
				if kind != NodeOther && nodeName(int(kind)) == "other" {
					return nil, fmt.Errorf("unknown node kind %d", kind)
				}
			}
		}
	}
	equalKinds := func(a, b []NodeKind) bool {
		if len(a) != len(b) {
			return false
		}
		for _, kind := range a {
			found := false
			for _, other := range b {
				if kind == other {
					found = true
				}
			}
			if !found {
				return false
			}
		}
		return true
	}
	for _, r := range seed {
		if r.Symmetric {
			if (r.Inverse != "" && r.Inverse != r.RelType) || !equalKinds(r.HeadKinds, r.TailKinds) {
				return nil, fmt.Errorf("invalid symmetric seed %s", r.RelType)
			}
		} else if r.Inverse != "" {
			var inverse *relTypeDef
			for i := range seed {
				if seed[i].RelType == r.Inverse {
					inverse = &seed[i]
				}
			}
			if inverse == nil || inverse.Symmetric || inverse.Inverse != r.RelType || !equalKinds(r.HeadKinds, inverse.TailKinds) || !equalKinds(r.TailKinds, inverse.HeadKinds) {
				return nil, fmt.Errorf("invalid inverse for %s", r.RelType)
			}
		}
	}
	kinds := func(list []NodeKind, names bool) string {
		out := make([]string, len(list))
		for i, k := range list {
			if names {
				out[i] = nodeName(int(k))
			} else {
				out[i] = strconv.Itoa(int(k))
			}
		}
		return strings.Join(out, ",")
	}
	cKinds := func(list []NodeKind) string {
		out := make([]string, 8)
		for i := range out {
			out[i] = "0"
			if i < len(list) {
				out[i] = strconv.Itoa(int(list[i]))
			}
		}
		return "{" + strings.Join(out, ", ") + "}"
	}
	bit := func(v bool) int {
		if v {
			return 1
		}
		return 0
	}
	sqlString := func(s string) string { return "'" + strings.ReplaceAll(s, "'", "''") + "'" }
	var tsv, native, db2, sql strings.Builder
	native.WriteString("// clang-format off\nstatic const rel_type_def_t SEED_ONTOLOGY[] = {\n")
	db2.WriteString("/* Code generated by the Go memory owner. DO NOT EDIT BY HAND. */\n#include \"db2_rel_seed.h\"\n#include \"db2_rel_type_helpers.h\"\n#include <string.h>\n\nstatic const db2_rel_seed_def_t DB2_SEED_ONTOLOGY[] = {\n")
	sql.WriteString("-- Generated by the Go memory owner; preserve existing operator definitions.\nINSERT INTO rel_types(rel_type,head_kinds,tail_kinds,is_symmetric,inverse_rel_type,correction_behavior,category,sensitivity,is_hierarchy_rel,status) VALUES\n")
	for i, r := range seed {
		fmt.Fprintf(&tsv, "%s\t%s\t%s\t%d\n", r.RelType, kinds(r.HeadKinds, false), kinds(r.TailKinds, false), r.Sensitivity)
		inverse := "NULL"
		if r.Inverse != "" {
			inverse = strconv.Quote(r.Inverse)
		}
		row := fmt.Sprintf("    {%s, %s, %d, %s, %d, %d, %s, %d, %s, %d, %d, 0},\n", strconv.Quote(r.RelType), cKinds(r.HeadKinds), len(r.HeadKinds), cKinds(r.TailKinds), len(r.TailKinds), bit(r.Symmetric), inverse, correction[r.Correction], strconv.Quote(r.Category), r.Sensitivity, bit(r.Hierarchy))
		native.WriteString(row)
		db2.WriteString(row)
		if i > 0 {
			sql.WriteString(",\n")
		}
		fmt.Fprintf(&sql, "(%s,%s,%s,%d,%s,%s,%s,%s,%d,'active')", sqlString(r.RelType), sqlString(kinds(r.HeadKinds, true)), sqlString(kinds(r.TailKinds, true)), bit(r.Symmetric), sqlString(r.Inverse), sqlString(r.Correction), sqlString(r.Category), sqlString([]string{"normal", "pii", "secret"}[r.Sensitivity]), bit(r.Hierarchy))
	}
	native.WriteString("};\n// clang-format on\n")
	sql.WriteString("\nON CONFLICT (rel_type) DO NOTHING;\n")
	db2.WriteString(`};

static const int DB2_SEED_COUNT =
    (int)(sizeof(DB2_SEED_ONTOLOGY) / sizeof(DB2_SEED_ONTOLOGY[0]));

int rel_types_seed_count(void)
{
   return DB2_SEED_COUNT;
}

const db2_rel_seed_def_t *rel_types_seed_at(int i)
{
   return (i >= 0 && i < DB2_SEED_COUNT) ? &DB2_SEED_ONTOLOGY[i] : NULL;
}

const db2_rel_seed_def_t *rel_types_seed_lookup(const char *rel_type)
{
   if (!rel_type || !rel_type[0])
      return NULL;
   char norm[DB2_REL_TYPE_NAME_MAX];
   rel_type_normalize(rel_type, norm, sizeof(norm));
   for (int i = 0; i < DB2_SEED_COUNT; i++)
      if (strcmp(DB2_SEED_ONTOLOGY[i].rel_type, norm) == 0)
         return &DB2_SEED_ONTOLOGY[i];
   return NULL;
}
`)
	return map[string]string{"tsv": tsv.String(), "native": native.String(), "db2": db2.String(), "sql": sql.String()}, nil
}
