-- Eval candidates and approach memory.
--
-- These two tables arrived upstream in src/modules/db1 while this branch was
-- replacing that module, so they are the one part of the C store with no Go
-- equivalent. src/db1_client already calls all ten operations (49-58): the
-- client side came across in an earlier merge, and without these tables those
-- calls reach the module and find no handler.
--
-- Column caps count BYTES (octet_length), matching the C buffers that read the
-- values back -- the unit correction migration 21 made everywhere else. The
-- number on each column is the C buffer minus its NUL.

CREATE TABLE IF NOT EXISTS eval_candidates (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  signature       TEXT NOT NULL UNIQUE CHECK (octet_length(signature) <= 32),
  -- Free text rather than an enum: the transition SQL is what enforces the
  -- reachable states, and an enum here would need a migration to add one.
  state           TEXT NOT NULL DEFAULT 'candidate' CHECK (octet_length(state) <= 15),
  suite           TEXT NOT NULL DEFAULT 'regressions',
  task_name       TEXT NOT NULL DEFAULT '',
  task_json       TEXT NOT NULL DEFAULT '{}' CHECK (octet_length(task_json) <= 4095),
  origin          TEXT NOT NULL DEFAULT '' CHECK (octet_length(origin) <= 31),
  origin_ref      TEXT NOT NULL DEFAULT '' CHECK (octet_length(origin_ref) <= 127),
  occurrences     BIGINT NOT NULL DEFAULT 1 CHECK (occurrences >= 0),
  -- The retained session set, capped at eight by the writer. jsonb rather than
  -- the C's TEXT: distinct_sessions is derived from it on every read, and
  -- jsonb_array_length does that in the query instead of parsing in the module.
  sessions        JSONB NOT NULL DEFAULT '[]'::jsonb
                    CHECK (jsonb_typeof(sessions) = 'array'),
  admitted_by     TEXT NOT NULL DEFAULT '' CHECK (octet_length(admitted_by) <= 31),
  admitted_path   TEXT NOT NULL DEFAULT '' CHECK (octet_length(admitted_path) <= 511),
  reject_reason   TEXT NOT NULL DEFAULT '' CHECK (octet_length(reject_reason) <= 255),
  passing_windows BIGINT NOT NULL DEFAULT 0 CHECK (passing_windows >= 0),
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS eval_candidates_state
  ON eval_candidates (state, updated_at DESC);

CREATE TABLE IF NOT EXISTS approach_failures (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  goal_signature     TEXT NOT NULL CHECK (octet_length(goal_signature) <= 32),
  goal_text          TEXT NOT NULL DEFAULT '' CHECK (octet_length(goal_text) <= 511),
  goal_tokens        TEXT NOT NULL DEFAULT '' CHECK (octet_length(goal_tokens) <= 511),
  approach_signature TEXT NOT NULL CHECK (octet_length(approach_signature) <= 32),
  approach_text      TEXT NOT NULL DEFAULT '' CHECK (octet_length(approach_text) <= 511),
  failure_mode       TEXT NOT NULL DEFAULT '' CHECK (octet_length(failure_mode) <= 255),
  source             TEXT NOT NULL DEFAULT '' CHECK (octet_length(source) <= 31),
  source_ref         TEXT NOT NULL DEFAULT '' CHECK (octet_length(source_ref) <= 127),
  occurrences        BIGINT NOT NULL DEFAULT 1 CHECK (occurrences >= 0),
  created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  -- The (goal, approach) pair is the identity: meeting the same dead end again
  -- is more evidence for one row, not a second row.
  UNIQUE (goal_signature, approach_signature)
);

CREATE INDEX IF NOT EXISTS approach_failures_ranked
  ON approach_failures (occurrences DESC, updated_at DESC, id DESC);
