-- Ensemble family: templated, turn-based multi-agent runs bound to a channel.

CREATE TABLE IF NOT EXISTS ensembles (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  template_name    TEXT   NOT NULL,
  channel          TEXT   NOT NULL DEFAULT 'general',
  status           TEXT   NOT NULL DEFAULT 'active',
  current_phase    BIGINT NOT NULL DEFAULT 0 CHECK (current_phase >= 0),
  current_turn     BIGINT NOT NULL DEFAULT 0 CHECK (current_turn >= 0),
  expected_agent   TEXT   NOT NULL DEFAULT '',
  expected_role    TEXT   NOT NULL DEFAULT '',
  paused_reason    TEXT   NOT NULL DEFAULT '',
  -- The template is stored with the run's assignments already bound into it,
  -- so the cast is fixed at creation. Re-resolving it per turn would let a
  -- template edited mid-run change who is expected to speak next.
  template_json    TEXT   NOT NULL DEFAULT '{}',
  assignments_json TEXT   NOT NULL DEFAULT '{}',
  context_json     TEXT   NOT NULL DEFAULT '[]',
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),

  -- The four states the module writes, and nothing else. 'complete' is
  -- terminal; a run that reads as something outside this set would fall to the
  -- ELSE branch of the channel ordering and be picked last forever without
  -- anything saying why.
  CONSTRAINT ensembles_status
    CHECK (status IN ('active', 'paused', 'complete', 'failed')),

  -- A paused run says why it paused; a run that is not paused has no reason to
  -- carry one. The C left stale reasons on rows it un-paused, so a reader
  -- could see an active run still claiming 'human_interruption'.
  CONSTRAINT ensembles_paused_reason
    CHECK ((status = 'paused') = (paused_reason <> ''))
);

-- ensemble_find_current_by_channel reads exactly this: a channel's runs, best
-- first.
CREATE INDEX IF NOT EXISTS ensembles_channel
  ON ensembles (channel, status, updated_at DESC);

CREATE INDEX IF NOT EXISTS ensembles_status
  ON ensembles (status, updated_at DESC);
