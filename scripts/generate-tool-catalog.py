#!/usr/bin/env python3
"""Generate the C tools owner's metadata from the shared, explicit catalog."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'server-go/modules/tools/catalog.json'
TARGET = ROOT / 'src/modules/tools/tool_catalog_data.h'
CLASSES = {'read': 1, 'write': 2, 'exec': 3, 'control': 4, 'remote': 5}
CATEGORIES = {name: 1 << i for i, name in enumerate(
    ('read', 'write', 'filesystem', 'network', 'external', 'execution', 'control'))}


def unique(pairs):
    result = {}
    for name, value in pairs:
        if name in result:
            raise ValueError('duplicate catalog field: ' + name)
        result[name] = value
    return result


def generate():
    catalog = json.loads(SOURCE.read_text(), object_pairs_hook=unique)
    lines = ['/* Generated by scripts/generate-tool-catalog.py; edit catalog.json. */',
             '// clang-format off',
             '#ifndef AIMEE_TOOL_CATALOG_DATA_H', '#define AIMEE_TOOL_CATALOG_DATA_H 1',
             '#include <aimee/tools/module_api.h>', '#include <string.h>',
             'typedef struct { const char *name; aimee_tool_metadata_t metadata; } aimee_tool_catalog_entry_t;',
             'static const aimee_tool_catalog_entry_t aimee_tool_catalog[] = {']
    for name, entry in sorted(catalog.items()):
        if not re.fullmatch(r'[a-z][a-z0-9_]{0,94}', name):
            raise ValueError('invalid tool name: ' + name)
        if set(entry) != {'class', 'side_effect', 'categories'}:
            raise ValueError('invalid metadata fields: ' + name)
        kind = CLASSES[entry['class']]
        primary = CATEGORIES[entry['side_effect']]
        categories = entry['categories']
        if not isinstance(categories, list) or len(set(categories)) != len(categories):
            raise ValueError('invalid categories: ' + name)
        mask = sum(CATEGORIES[value] for value in categories)
        if not mask & primary:
            raise ValueError('primary category missing: ' + name)
        lines.append('   {"%s", {%du, %du, %du}},' % (name, kind, primary, mask))
    if not catalog:
        raise ValueError('empty catalog')
    lines += ['};',
              'static inline aimee_tool_metadata_t aimee_tools_catalog_metadata(const char *name)',
              '{',
              '   if (!name || !name[0]) return (aimee_tool_metadata_t){0};',
              '   for (size_t i = 0; i < sizeof(aimee_tool_catalog) / sizeof(aimee_tool_catalog[0]); ++i)',
              '      if (strcmp(name, aimee_tool_catalog[i].name) == 0) return aimee_tool_catalog[i].metadata;',
              "   if (strchr(name, ':'))",
              '      return (aimee_tool_metadata_t){AIMEE_TOOL_CLASS_REMOTE, AIMEE_TOOL_POLICY_EXTERNAL,',
              '                                      AIMEE_TOOL_POLICY_EXTERNAL | AIMEE_TOOL_POLICY_NETWORK};',
              '   return (aimee_tool_metadata_t){0};', '}', '#endif', '// clang-format on', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = generate()
    if args.check:
        if TARGET.read_text() != output:
            raise SystemExit('tool catalog is stale; run scripts/generate-tool-catalog.py')
    else:
        TARGET.write_text(output)


if __name__ == '__main__':
    main()
