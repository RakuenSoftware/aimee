/* gen-memory-ontology-seed.c: emit the seed ontology the Go memory module uses,
 * asked of the compiled C table rather than parsed out of its source.
 *
 * Parsing src/rel_types.c was tried first and silently produced a different row
 * count -- a grep was also counting the separate alias table. Walking
 * rel_types_seed_count/rel_types_seed_at is the authority. Regenerate after any
 * change to SEED_ONTOLOGY:
 *
 *   cc -std=c11 -Wall -Wextra -Isrc -Isrc/headers -o /tmp/gen-seed \
 *      scripts/gen-memory-ontology-seed.c src/rel_types.c
 *   /tmp/gen-seed server-go/modules/memory/ontology_seed.go \
 *                 server-go/modules/memory/testdata/ontology_seed.tsv \
 *                 src/modules/db2/support/rel_seed_primitives.c
 *
 * The Go outputs carry only the fields the memory module reads. The optional
 * DB2 output carries the complete row needed by its PostgreSQL commit path. */
#include "rel_types.h"

#include <stdio.h>
#include <stdlib.h>

/* Every emitted format is deliberately text-only. Reject hidden control or
 * non-ASCII bytes before opening any output so Go, TSV, and C cannot interpret
 * the same compiled seed differently. */
static void validate_seed_string(const char *field, int row, const char *value)
{
   if (!value)
      return;
   for (const unsigned char *p = (const unsigned char *)value; *p; p++)
      if (*p < 0x20 || *p > 0x7e)
      {
         fprintf(stderr, "seed row %d field %s contains non-printable byte 0x%02x\n",
                 row, field, (unsigned int)*p);
         exit(1);
      }
}

static void validate_seed_strings(void)
{
   for (int i = 0; i < rel_types_seed_count(); i++)
   {
      const rel_type_def_t *def = rel_types_seed_at(i);
      if (!def)
      {
         fprintf(stderr, "seed row %d is NULL\n", i);
         exit(1);
      }
      validate_seed_string("rel_type", i, def->rel_type);
      validate_seed_string("inverse_rel_type", i, def->inverse_rel_type);
      validate_seed_string("category", i, def->category);
   }
}

/* The Go NodeKind constant naming, so the generated table reads like hand-written
 * Go rather than a list of integers. Anything unnamed is a seed row referring to
 * a kind the Go port does not model, which must fail loudly, not silently emit
 * an integer that compiles. */
static const char *go_node_kind(memory_node_kind_t kind)
{
   switch (kind)
   {
   case NODE_FILE: return "NodeFile";
   case NODE_FUNCTION: return "NodeFunction";
   case NODE_STRUCT: return "NodeStruct";
   case NODE_MODULE: return "NodeModule";
   case NODE_BUG: return "NodeBug";
   case NODE_COMMIT: return "NodeCommit";
   case NODE_PR: return "NodePr";
   case NODE_DEVELOPER: return "NodeDeveloper";
   case NODE_CONCEPT: return "NodeConcept";
   case NODE_EVENT: return "NodeEvent";
   case NODE_PERSON: return "NodePerson";
   case NODE_PLACE: return "NodePlace";
   case NODE_TIME_EXPR: return "NodeTimeExpr";
   case NODE_DEVICE: return "NodeDevice";
   case NODE_ORG: return "NodeOrg";
   case NODE_IP: return "NodeIp";
   case NODE_SCALAR: return "NodeScalar";
   case NODE_OTHER: return "NodeOther";
   default: return NULL;
   }
}

static const char *go_sensitivity(rel_sensitivity_t sens)
{
   switch (sens)
   {
   case SENS_NORMAL: return "SensNormal";
   case SENS_PII: return "SensPII";
   case SENS_SECRET: return "SensSecret";
   default: return NULL;
   }
}

static void write_kind_list(FILE *f, const memory_node_kind_t *kinds, int count)
{
   fputs("[]NodeKind{", f);
   for (int i = 0; i < count; i++)
   {
      const char *name = go_node_kind(kinds[i]);
      if (!name)
      {
         fprintf(stderr, "seed row uses node kind %d, which the Go port does not name\n", kinds[i]);
         exit(1);
      }
      fprintf(f, "%s%s", i ? ", " : "", name);
   }
   fputc('}', f);
}

static void write_go(const char *path)
{
   FILE *f = fopen(path, "w");
   if (!f)
   {
      perror(path);
      exit(1);
   }
   fputs("// Code generated by scripts/gen-memory-ontology-seed.c from src/rel_types.c\n"
         "// SEED_ONTOLOGY. DO NOT EDIT BY HAND.\n"
         "// Regenerate when the C table changes; ontology_conformance_test.go compares\n"
         "// this against testdata/ontology_seed.tsv, generated in the same walk.\n"
         "\n"
         "package memory\n"
         "\n"
         "// seedOntology is the memory module's relation table: the entity kinds the\n"
         "// write gate allows at each end, and the sensitivity tier the recall gate\n"
         "// reads. NodeOther in a kind list is the ANY wildcard.\n"
         "var seedOntology = []relTypeDef{\n",
         f);
   for (int i = 0; i < rel_types_seed_count(); i++)
   {
      const rel_type_def_t *def = rel_types_seed_at(i);
      const char *sens = go_sensitivity(def->sensitivity);
      if (!sens)
      {
         fprintf(stderr, "seed row %s has sensitivity %d, which the Go port does not name\n",
                 def->rel_type, def->sensitivity);
         exit(1);
      }
      fprintf(f, "\t{RelType: \"%s\", HeadKinds: ", def->rel_type);
      write_kind_list(f, def->head_kinds, def->head_kind_count);
      fputs(", TailKinds: ", f);
      write_kind_list(f, def->tail_kinds, def->tail_kind_count);
      fprintf(f, ", Sensitivity: %s},\n", sens);
   }
   fputs("}\n", f);
   fclose(f);
}

static void write_kind_field(FILE *f, const memory_node_kind_t *kinds, int count)
{
   for (int i = 0; i < count; i++)
      fprintf(f, "%s%d", i ? ";" : "", (int)kinds[i]);
}

static void write_tsv(const char *path)
{
   FILE *f = fopen(path, "w");
   if (!f)
   {
      perror(path);
      exit(1);
   }
   for (int i = 0; i < rel_types_seed_count(); i++)
   {
      const rel_type_def_t *def = rel_types_seed_at(i);
      fprintf(f, "%s\t", def->rel_type);
      write_kind_field(f, def->head_kinds, def->head_kind_count);
      fputc('\t', f);
      write_kind_field(f, def->tail_kinds, def->tail_kind_count);
      fprintf(f, "\t%d\n", (int)def->sensitivity);
   }
   fclose(f);
}

static void write_c_string(FILE *f, const char *value)
{
   if (!value)
   {
      fputs("NULL", f);
      return;
   }
   fputc('"', f);
   for (const unsigned char *p = (const unsigned char *)value; *p; p++)
   {
      if (*p == '"' || *p == '\\')
         fprintf(f, "\\%c", *p);
      else
         fputc(*p, f);
   }
   fputc('"', f);
}

static void write_c_kinds(FILE *f, const memory_node_kind_t *kinds)
{
   fputc('{', f);
   for (int i = 0; i < REL_TYPE_MAX_KINDS; i++)
      fprintf(f, "%s%d", i ? ", " : "", (int)kinds[i]);
   fputc('}', f);
}

/* DB2 must carry the complete seed row because its PostgreSQL commit path reads
 * correction, inverse, category, hierarchy, and status in addition to the
 * memory module's gate fields. Generate that copy from the compiled authority
 * in the same walk instead of maintaining a second handwritten table. */
static void write_db2_c(const char *path)
{
   FILE *f = fopen(path, "w");
   if (!f)
   {
      perror(path);
      exit(1);
   }
   fputs("/* Code generated by scripts/gen-memory-ontology-seed.c from the compiled\n"
         " * src/rel_types.c SEED_ONTOLOGY. DO NOT EDIT BY HAND. */\n"
         "#include \"db2_rel_seed.h\"\n"
         "#include \"db2_rel_type_helpers.h\"\n"
         "#include <string.h>\n\n"
         "static const db2_rel_seed_def_t DB2_SEED_ONTOLOGY[] = {\n",
         f);
   for (int i = 0; i < rel_types_seed_count(); i++)
   {
      const rel_type_def_t *def = rel_types_seed_at(i);
      fputs("    {", f);
      write_c_string(f, def->rel_type);
      fputs(", ", f);
      write_c_kinds(f, def->head_kinds);
      fprintf(f, ", %d, ", def->head_kind_count);
      write_c_kinds(f, def->tail_kinds);
      fprintf(f, ", %d, %d, ", def->tail_kind_count, def->is_symmetric);
      write_c_string(f, def->inverse_rel_type);
      fprintf(f, ", %d, ", (int)def->correction_behavior);
      write_c_string(f, def->category);
      fprintf(f, ", %d, %d, %d},\n", (int)def->sensitivity,
              def->is_hierarchy_rel, (int)def->status);
   }
   fputs("};\n\n"
         "static const int DB2_SEED_COUNT =\n"
         "    (int)(sizeof(DB2_SEED_ONTOLOGY) / sizeof(DB2_SEED_ONTOLOGY[0]));\n\n"
         "int rel_types_seed_count(void)\n"
         "{\n"
         "   return DB2_SEED_COUNT;\n"
         "}\n\n"
         "const db2_rel_seed_def_t *rel_types_seed_at(int i)\n"
         "{\n"
         "   return (i >= 0 && i < DB2_SEED_COUNT) ? &DB2_SEED_ONTOLOGY[i] : NULL;\n"
         "}\n\n"
         "const db2_rel_seed_def_t *rel_types_seed_lookup(const char *rel_type)\n"
         "{\n"
         "   if (!rel_type || !rel_type[0])\n"
         "      return NULL;\n"
         "   char norm[DB2_REL_TYPE_NAME_MAX];\n"
         "   rel_type_normalize(rel_type, norm, sizeof(norm));\n"
         "   for (int i = 0; i < DB2_SEED_COUNT; i++)\n"
         "      if (strcmp(DB2_SEED_ONTOLOGY[i].rel_type, norm) == 0)\n"
         "         return &DB2_SEED_ONTOLOGY[i];\n"
         "   return NULL;\n"
         "}\n",
         f);
   fclose(f);
}

int main(int argc, char **argv)
{
   if (argc != 3 && argc != 4)
   {
      fprintf(stderr,
              "usage: %s <ontology_seed.go> <ontology_seed.tsv> [db2_rel_seed.c]\n",
              argv[0]);
      return 2;
   }
   validate_seed_strings();
   write_go(argv[1]);
   write_tsv(argv[2]);
   if (argc == 4)
      write_db2_c(argv[3]);
   return 0;
}
