"""Generate live probes for catalogued operations that have none.

A probe proves one thing: that an operation's statement parses, binds and runs
against a real schema. The hand-written probes carry meaningful arguments and
assert on what comes back; these carry the contract's own minimum-valid
arguments and assert only that the reply decodes.

That is deliberately the weaker of the two. The parity run is what exercises
every operation with the arguments the C replay makes and compares the answers;
these exist so that an operation cannot be added without SOMETHING having run it
against Postgres, which is what TestLiveCoversEveryPortedOperation is for.

    python3 scripts/gen_db2_live_probes.py --write
"""
import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

CONTRACT = Path("server-go/db2/contract_generated.go")
CATALOG = Path("src/modules/db2/eventcontract/operations.json")
MODULE = Path("server-go/modules/db2")
TARGET = MODULE / "op_live_generated_test.go"


def contract_names() -> dict:
    text = CONTRACT.read_text()
    stages = dict(re.findall(r"^const Stage(\w+) = Family(\w+)$", text, re.M))
    operations = {name: int(value) for name, value in
                  re.findall(r"^const Operation(\w+) uint32 = (\d+)$", text, re.M)}
    families = {name: int(value) for name, value in
                re.findall(r"^const Family(\w+) uint32 = (\d+)$", text, re.M)}
    return {(families[f], operations[n]): n
            for n, f in stages.items() if n in operations and f in families}


def probed() -> set:
    """Operation constants that already have a hand-written probe."""
    names = set()
    for path in MODULE.glob("op_live*.go"):
        if path.name == TARGET.name:
            continue
        names |= set(re.findall(r"db2contract\.Stage(\w+)\b", path.read_text()))
    return names


def request_signature(text: str, name: str):
    match = re.search(rf"^func Encode{name}Request\(([^)]*)\) ", text, re.M)
    if not match:
        return None
    params = match.group(1).strip()
    if not params:
        return []
    fields = []
    for group in params.split(","):
        group = group.strip()
        if not group:
            continue
        fields.append(group)
    # Go allows "a, b string"; expand the shared-type form.
    expanded, pending = [], []
    for field in fields:
        parts = field.split()
        if len(parts) == 1:
            pending.append(parts[0])
            continue
        pending.append(parts[0])
        for _ in pending:
            expanded.append(parts[-1])
        pending = []
    return expanded


# Operations whose minimum-valid argument is still not a usable one.
#
# The envelope bounds a field's length, never its shape. Where a string is
# handed to Postgres as an interval modifier, "a" satisfies the envelope and
# fails the statement -- so the probe would report a working operation as
# broken. These say what a usable argument looks like instead.
ARGUMENT_OVERRIDES = {
    "entity_profile_fresh": ['"a"', '"-1 days"'],
}


def minimum_for(kind: str, bounds: dict, index: int) -> str:
    """The smallest argument the envelope accepts.

    One rather than zero for every number: several fields declare a minimum of
    one -- an identifier, a limit -- and none declares a maximum below it, so one
    is the value that satisfies every bound the contract sets.
    """
    if kind == "string":
        return '"a"'
    if kind == "float64":
        return "1"
    return "1"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()

    text = CONTRACT.read_text()
    catalog = json.loads(CATALOG.read_text())
    stage_of = {f["name"]: int(f["id"]) for f in catalog["families"]}
    names = contract_names()
    already = probed()

    missing = []
    for op in catalog["operations"]:
        key = (stage_of.get(op["family"]), int(op["id"]))
        name = names.get(key)
        if name is None or name in already:
            continue
        missing.append((op, name))

    lines = [
        "package db2",
        "",
        "// Code generated by scripts/gen_db2_live_probes.py. DO NOT EDIT.",
        "//",
        "// One probe per catalogued operation that has no hand-written one. Each",
        "// sends the contract's minimum-valid request and asserts only that the",
        "// operation ran and its reply decodes -- which is what proves the statement",
        "// parses and binds against a real schema.",
        "//",
        "// The parity run is what checks the ANSWERS: it replays the C's own requests",
        "// and compares them byte for byte. These exist so no operation can be added",
        "// without something having run it against Postgres.",
        "",
        "import (",
        '\t"testing"',
        "",
        '\tdb2contract "github.com/JBailes/aimee/server-go/db2"',
        ")",
        "",
        "func liveGeneratedProbes() []liveRequest {",
        "\treturn []liveRequest{",
    ]
    emitted = 0
    skipped = []
    for op, name in missing:
        params = request_signature(text, name)
        if params is None:
            skipped.append(name)
            continue
        override = ARGUMENT_OVERRIDES.get(str(op["name"]))
        if override is not None:
            arguments = ", ".join(override)
        else:
            arguments = ", ".join(minimum_for(kind, {}, index)
                                  for index, kind in enumerate(params))
        encode_returns_error = re.search(
            rf"^func Encode{name}Request\([^)]*\) \(\[\]byte, error\)", text, re.M)
        lines.append("\t\t{")
        lines.append(f'\t\t\tname:  "{op["family"]}.{op["name"]}",')
        lines.append(f"\t\t\tstage: db2contract.Stage{name},")
        lines.append("\t\t\tgenerated: true,")
        lines.append("\t\t\tencode: func() ([]byte, error) {")
        if encode_returns_error:
            lines.append(
                f"\t\t\t\treturn db2contract.Encode{name}Request({arguments})")
        else:
            lines.append(
                f"\t\t\t\treturn db2contract.Encode{name}Request({arguments}), nil")
        lines.append("\t\t\t},")
        lines.append("\t\t\tdecoded: func(t *testing.T, body []byte) {")
        decode_match = re.search(
            rf"^func Decode{name}Reply\(reply \[\]byte\) \(([^)]*)\)", text, re.M)
        if decode_match and decode_match.group(1).strip() == "error":
            lines.append(
                f"\t\t\t\tif err := db2contract.Decode{name}Reply(body); err != nil {{")
            lines.append('\t\t\t\t\tt.Fatalf("decode reply: %v", err)')
            lines.append("\t\t\t\t}")
        elif decode_match:
            count = len(decode_match.group(1).split(","))
            blanks = ", ".join(["_"] * (count - 1))
            lines.append(
                f"\t\t\t\tif {blanks}, err := db2contract.Decode{name}Reply(body); "
                "err != nil {")
            lines.append('\t\t\t\t\tt.Fatalf("decode reply: %v", err)')
            lines.append("\t\t\t\t}")
        else:
            lines.append("\t\t\t\t_ = body")
        lines.append("\t\t\t},")
        lines.append("\t\t},")
        emitted += 1
    lines.append("\t}")
    lines.append("}")
    lines.append("")

    rendered = "\n".join(lines)
    if args.write:
        TARGET.write_text(rendered)
        subprocess.run(["gofmt", "-w", str(TARGET)], check=False)
        print(f"wrote {TARGET}: {emitted} probes")
        if skipped:
            print(f"  skipped (no request encoder): {skipped}")
        return 0
    print(f"would emit {emitted} probes; skipped {len(skipped)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
