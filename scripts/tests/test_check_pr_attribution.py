#!/usr/bin/env python3
"""Exercise text attribution, GitHub's app badge, and fail-closed API input."""
import importlib.util
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "scripts/check-pr-attribution.py"
SPEC = importlib.util.spec_from_file_location("pr_attribution", SOURCE)
CHECKER = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(CHECKER)


def issue(app=None, body="Fix browser chat."):
    return {"number": 3036, "title": "Browser chat", "body": body, "performed_via_github_app": app}


class AttributionTests(unittest.TestCase):
    def test_human_pr_with_no_app_passes(self):
        self.assertEqual(CHECKER.violations(issue()), [])
        self.assertEqual(CHECKER.violations(issue(body=None)), [])

    def test_both_reported_app_badges_fail_without_a_footer(self):
        for app in ({"id": 1236702, "slug": "claude", "name": "Claude"},
                    {"id": 1144995, "slug": "chatgpt-codex-connector", "name": "ChatGPT Codex Connector"}):
            with self.subTest(app=app["slug"]):
                self.assertIn("performed_via_github_app", CHECKER.violations(issue(app))[0])

    def test_known_identity_cannot_hide_behind_renamed_display_fields(self):
        self.assertTrue(CHECKER.violations(issue({"id": 1144995, "slug": "renamed", "name": "Renamed"})))
        self.assertTrue(CHECKER.violations(issue({"id": 1, "slug": "CLAUDE", "name": "Renamed"})))

    def test_non_ai_app_is_not_rejected(self):
        self.assertEqual(CHECKER.violations(issue({"id": 2, "slug": "release-maintenance", "name": "Release maintenance"})), [])

    def test_footers_and_existing_trailers_fail(self):
        for text in ("_Generated by [Claude Code](https://claude.ai/code)_", "*Generated by [Claude Code](https://claude.ai/code)*", "Generated with [Codex](https://example.com)",
                     "Co-authored-by: Example <example@example.com>", "Codex-Session: https://example.com/one",
                     "https://example.com/code/session_123", "**Generated by [ChatGPT Codex Connector](https://example.com)**"):
            with self.subTest(text=text):
                self.assertTrue(CHECKER.violations(issue(body="Changes\n\n" + text)))

    def test_explanatory_prose_and_documentation_links_pass(self):
        self.assertEqual(CHECKER.violations(issue(body="Reject Generated by [Claude Code] footers.\nhttps://claude.ai/docs")), [])

    def test_incomplete_or_wrong_api_representations_fail_closed(self):
        for data in ({}, {"number": 3036, "title": "x", "body": "x"}, issue("claude"),
                     issue({"id": 1144995}), issue({"id": True, "slug": "x"}), []):
            with self.subTest(data=data):
                with self.assertRaises(ValueError):
                    CHECKER.violations(data)

    def test_cli_rejects_app_badge_and_malformed_json(self):
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / "issue.json"
            for data, code in ((issue(), 0), (issue({"id": 1236702, "slug": "claude"}), 1), ({}, 1)):
                path.write_text(json.dumps(data))
                result = subprocess.run([sys.executable, str(SOURCE), str(path)], capture_output=True, text=True)
                self.assertEqual(result.returncode, code, result.stderr)
            path.write_text("not JSON")
            self.assertEqual(subprocess.run([sys.executable, str(SOURCE), str(path)], capture_output=True).returncode, 1)


if __name__ == "__main__":
    unittest.main()
