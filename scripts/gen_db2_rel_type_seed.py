"""Generate the Go copy of the relation-type seed ontology from the C table.

The ontology lives in src/rel_types.c as a static table, and both the C module
and the Go module have to seed the same rows -- a graph refuses to store an edge
whose relation has no row here, so a Go module seeding a different set would
accept a different set of edges.

Transcribing forty-four entries by hand would have worked exactly once. This
reads the C and emits the Go, and the test beside the generated file re-runs it
to prove the two have not drifted.

    python3 scripts/gen_db2_rel_type_seed.py --check   # fail on drift
    python3 scripts/gen_db2_rel_type_seed.py --write   # regenerate
"""
import argparse
import re
import sys
from pathlib import Path

SOURCE = Path("src/rel_types.c")
KIND_TEXT_SOURCE = Path("src/modules/db2/support/node_kind_text_primitives.c")
TARGET = Path("server-go/modules/db2/rel_type_seed_generated.go")

CORRECTION_TEXT = {
    "CORR_SUPERSEDE": "supersede",
    "CORR_HARD_DELETE": "hard_delete",
    "CORR_IMMUTABLE": "immutable",
}
SENSITIVITY_TEXT = {
    "SENS_NORMAL": "normal",
    "SENS_PII": "pii",
    "SENS_SECRET": "secret",
}


def node_kind_text() -> dict:
    """NODE_* -> the text the C writes, read from the primitives table.

    Anything the switch does not name falls through to its default, "other" --
    which is how NODE_OTHER itself is spelled, since the enum reserves 99 for it
    rather than giving it a case.
    """
    text = KIND_TEXT_SOURCE.read_text()
    pairs = re.findall(r"case DB2_(NODE_\w+):\s*\n\s*return \"([^\"]+)\";", text)
    mapping = {name: value for name, value in pairs}
    mapping.setdefault("NODE_OTHER", "other")
    return mapping


def parse_seed(text: str) -> list:
    start = text.index("SEED_ONTOLOGY[] = {")
    end = text.index("\n};", start)
    body = text[start:end]
    entries = []
    # Each entry opens with {"name", and the fields follow in declaration order.
    for match in re.finditer(r'\{"([a-z_]+)",\s*(.*?)\n\s*REL_STATUS_\w+\}', body, re.S):
        name, rest = match.group(1), match.group(2)
        head = re.search(r"\{([^}]*)\},\s*(\d+),", rest)
        tail = re.search(r"\},\s*\d+,\s*\{([^}]*)\},\s*(\d+),", rest)
        if not head or not tail:
            raise SystemExit(f"could not parse the kinds of {name}")
        after_tail = rest[tail.end():]
        fields = [f.strip() for f in after_tail.split(",")]
        symmetric = fields[0]
        inverse = fields[1]
        correction = fields[2]
        category = fields[3]
        sensitivity = fields[4]
        hierarchy = fields[5]
        entries.append({
            "rel_type": name,
            "head_kinds": [k.strip() for k in head.group(1).split(",") if k.strip()],
            "head_count": int(head.group(2)),
            "tail_kinds": [k.strip() for k in tail.group(1).split(",") if k.strip()],
            "tail_count": int(tail.group(2)),
            "is_symmetric": int(symmetric),
            "inverse": "" if inverse == "NULL" else inverse.strip('"'),
            "correction": CORRECTION_TEXT[correction],
            "category": "" if category == "NULL" else category.strip('"'),
            "sensitivity": SENSITIVITY_TEXT[sensitivity],
            "is_hierarchy": int(hierarchy),
        })
    return entries


def render(entries: list, kinds: dict) -> str:
    lines = [
        "package db2",
        "",
        "// Code generated by scripts/gen_db2_rel_type_seed.py. DO NOT EDIT.",
        "//",
        "// The relation ontology the graph seeds itself with, from the C's",
        "// SEED_ONTOLOGY in src/rel_types.c. Both modules have to seed the same rows:",
        "// an edge whose relation has no row here cannot be stored, so a Go module",
        "// seeding a different set would accept a different graph.",
        "",
        "// relTypeSeed is one row of the seeded ontology, already rendered into the",
        "// text the table holds -- the kind lists are comma-joined and the enums are",
        "// spelled as the C spells them.",
        "type relTypeSeed struct {",
        "\tRelType            string",
        "\tHeadKinds          string",
        "\tTailKinds          string",
        "\tIsSymmetric        int",
        "\tInverseRelType     string",
        "\tCorrectionBehavior string",
        "\tCategory           string",
        "\tSensitivity        string",
        "\tIsHierarchyRel     int",
        "}",
        "",
        "var relTypeSeedOntology = []relTypeSeed{",
    ]
    for entry in entries:
        head = ",".join(kinds[k] for k in entry["head_kinds"][: entry["head_count"]])
        tail = ",".join(kinds[k] for k in entry["tail_kinds"][: entry["tail_count"]])
        lines.append("\t{")
        lines.append(f'\t\tRelType:            "{entry["rel_type"]}",')
        lines.append(f'\t\tHeadKinds:          "{head}",')
        lines.append(f'\t\tTailKinds:          "{tail}",')
        lines.append(f'\t\tIsSymmetric:        {entry["is_symmetric"]},')
        lines.append(f'\t\tInverseRelType:     "{entry["inverse"]}",')
        lines.append(f'\t\tCorrectionBehavior: "{entry["correction"]}",')
        lines.append(f'\t\tCategory:           "{entry["category"]}",')
        lines.append(f'\t\tSensitivity:        "{entry["sensitivity"]}",')
        lines.append(f'\t\tIsHierarchyRel:     {entry["is_hierarchy"]},')
        lines.append("\t},")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    entries = parse_seed(SOURCE.read_text())
    if not entries:
        print("no seed entries parsed", file=sys.stderr)
        return 1
    rendered = render(entries, node_kind_text())

    if args.write:
        TARGET.write_text(rendered)
        print(f"wrote {TARGET} ({len(entries)} relation types)")
        return 0
    if args.check:
        if not TARGET.exists():
            print(f"{TARGET} is missing; run with --write", file=sys.stderr)
            return 1
        if TARGET.read_text() != rendered:
            print(f"{TARGET} is out of date with {SOURCE}; run with --write",
                  file=sys.stderr)
            return 1
        print(f"ok: {len(entries)} relation types match {SOURCE}")
        return 0
    print(rendered)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
