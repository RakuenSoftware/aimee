-- Phase 3: code graph projection ledger.
-- code_projection_generations tracks one generation per project:
--   pending -> visible (on publish), pending -> aborted (on failure),
--   visible -> superseded (on next publish). At most one 'visible' per project.
CREATE TABLE IF NOT EXISTS code_projection_generations (
    id          BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    project     TEXT NOT NULL,
    state       TEXT NOT NULL DEFAULT 'pending'
                    CHECK (state IN ('pending','visible','superseded','aborted')),
    source_hash TEXT NOT NULL DEFAULT '',
    edge_count  BIGINT NOT NULL DEFAULT 0,
    node_count  BIGINT NOT NULL DEFAULT 0,
    started_at  TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')),
    visible_at  TEXT NOT NULL DEFAULT '',
    aborted_at  TEXT NOT NULL DEFAULT '',
    error       TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_cpg_project_state
    ON code_projection_generations(project, state);
CREATE UNIQUE INDEX IF NOT EXISTS idx_cpg_one_visible_project
    ON code_projection_generations(project)
    WHERE state = 'visible';

-- Mutation bookkeeping: projected-edge membership per generation.
-- Not joined in hot recall path; used for publish, rollback, and cleanup.
CREATE TABLE IF NOT EXISTS code_projection_edges (
    generation_id BIGINT NOT NULL REFERENCES code_projection_generations(id)
        ON DELETE CASCADE,
    project       TEXT NOT NULL,
    source        TEXT NOT NULL,
    relation      TEXT NOT NULL,
    target        TEXT NOT NULL,
    source_hash   TEXT NOT NULL DEFAULT '',
    PRIMARY KEY (generation_id, source, relation, target)
);
CREATE INDEX IF NOT EXISTS idx_cpe_project_triple
    ON code_projection_edges(project, source, relation, target);

