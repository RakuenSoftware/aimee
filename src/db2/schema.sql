            value         TEXT NOT NULL DEFAULT '',
            claim_kind    TEXT NOT NULL DEFAULT '',
            payload_json  TEXT NOT NULL DEFAULT ''
        )
    $T$;

    -- curator_code_unit_vectors: pgvector embeddings for deep-curator
    -- per-definition semantic code store. One point per resolved code
    -- definition (function/struct/typedef/etc.) with three named vector
    -- columns: intent_vec (what the definition is trying to do),
    -- signature_vec (the parameter/return shape), and body_vec (the
