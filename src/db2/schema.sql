    -- store (one point per resolved claim artifact) used by detect_contradictions
    -- to match on subject+attribute (subj_attr_vec) and anti-match on the
    -- claim's value (value_vec). Two named vector columns per row, with
    -- artifact_id / subject / attribute / value / claim_kind for filtering
    -- and provenance.
    EXECUTE $T$
