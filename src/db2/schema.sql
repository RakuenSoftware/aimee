    $T$;

    EXECUTE $T$
        CREATE TABLE IF NOT EXISTS kb_embeddings (
            point_id     BIGINT PRIMARY KEY,
            embedding    vector(384),
            project      TEXT NOT NULL DEFAULT '',
            payload_json TEXT NOT NULL DEFAULT ''
