-- DB2 temporal helpers (postgres-native). DB2 stores wall-clock timestamps
-- as TEXT in canonical UTC format 'YYYY-MM-DD HH24:MI:SS'. pg_now_text()
-- returns "now" in that format; the modifier overload returns "now + interval"
-- where the modifier is a postgres interval string ('+7 days', '-30 days',
-- '-1800 seconds', etc.). julianday() / datetime() sqlite-compat shims that
-- previously sat here have been retired — application SQL now emits native
-- pg_now_text() and EXTRACT(EPOCH FROM x::timestamp)/86400.0 directly.
CREATE OR REPLACE FUNCTION pg_now_text() RETURNS TEXT AS $$
  SELECT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS');
$$ LANGUAGE SQL STABLE;
CREATE OR REPLACE FUNCTION pg_now_text(modifier TEXT) RETURNS TEXT AS $$
  SELECT to_char((now() AT TIME ZONE 'UTC') + (modifier)::interval,
                 'YYYY-MM-DD HH24:MI:SS');
$$ LANGUAGE SQL STABLE;
