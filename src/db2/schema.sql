-- set_tenant_context(principal, team): the ONLY runtime path that sets the tenant
-- GUCs. SECURITY DEFINER, EXECUTE granted to the runtime role only (B4/N4). It
-- sets aimee.principal first, then validates team membership UNDER that principal's
-- own-rows policy (so it needs no BYPASSRLS), then sets aimee.team. A team not in
-- the principal's memberships raises (insufficient_privilege), fail-closed.
CREATE OR REPLACE FUNCTION set_tenant_context(p_principal TEXT, p_team BIGINT)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF p_principal IS NULL OR p_principal = '' THEN
    RAISE EXCEPTION 'set_tenant_context: empty principal' USING ERRCODE = '42501';
  END IF;
  PERFORM set_config('aimee.principal', p_principal, true);  -- transaction-local
  IF p_team IS NOT NULL AND p_team > 0 THEN
    IF NOT EXISTS (SELECT 1 FROM kb_team_membership
                   WHERE identity_key = p_principal AND team = p_team) THEN
      RAISE EXCEPTION 'set_tenant_context: team % not in principal memberships', p_team
        USING ERRCODE = '42501';
    END IF;
    PERFORM set_config('aimee.team', p_team::text, true);
  ELSE
    PERFORM set_config('aimee.team', '', true);
  END IF;
END
$$;

-- Enable + FORCE RLS so even the table owner cannot bypass the predicate; the
-- runtime role is non-owner + NOBYPASSRLS (schema_roles.sql). missing_ok=true on
-- current_setting so an unset GUC yields NULL -> no rows (fail-closed), never an error.
DO $$
DECLARE t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY['kb_team','kb_project','kb_team_membership','kb_project_membership','kb_admin_grant']
  LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', t);
  END LOOP;
END
$$;

