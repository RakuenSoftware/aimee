    -- resolution (resolve_entities pass). Mirrors kb_embeddings with the
    -- additional scope_kind / scope_id / canonical_name columns the curator
    -- needs for filtering candidate entities, plus artifact_id so a matched
    -- point_id can be reverse-mapped to its source entity artifact (used by
