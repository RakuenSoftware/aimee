CREATE OR REPLACE FUNCTION lessons_ledger_immutable() RETURNS trigger AS $$
BEGIN
  IF (TG_OP = 'DELETE' OR TG_OP = 'TRUNCATE') THEN
    RAISE EXCEPTION 'lessons_outcome_ledger is append-only (% forbidden)', TG_OP;
  END IF;
  -- UPDATE: everything but the confirmation columns is immutable.
  IF ROW(NEW.id, NEW.session_id, NEW.turn_id, NEW.project_id, NEW.generation_id,
         NEW.answer_outcome, NEW.correction_text, NEW.finding_id, NEW.actor_id,
         NEW.actor_source, NEW.ts)
     IS DISTINCT FROM
     ROW(OLD.id, OLD.session_id, OLD.turn_id, OLD.project_id, OLD.generation_id,
         OLD.answer_outcome, OLD.correction_text, OLD.finding_id, OLD.actor_id,
         OLD.actor_source, OLD.ts) THEN
    RAISE EXCEPTION 'lessons_outcome_ledger is append-only (only confirmation may change)';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

