-- kb_doc_assets: visual crops (figures/tables/pages) rendered from a PDF (structured-PDF
-- Phase C). The crop BYTES live in the content-addressed blob store (one file per sha256);
-- blob_ref is that sha256 — a KB-INTERNAL identifier never returned to a client, never in a
-- URL/log/error, and the blob dir is served by no file route. The sole client read path is
-- open_asset, keyed on the OPAQUE row id (kb_doc_assets.id, never sha256-derived), which
-- applies the caller's auth + the live document_key ACL + an access audit-log entry before
